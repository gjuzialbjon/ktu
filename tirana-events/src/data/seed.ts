/** Day offsets keep the seed feed always "this week", whenever the demo runs. */
const at = (daysFromNow: number, hour: number, minute = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + daysFromNow);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

const ago = (hours: number): string => new Date(Date.now() - hours * 3600_000).toISOString();

/**
 * Later today, so "today" always has something whenever the demo runs. Early in the day
 * events sit on the hour; late in the evening the same offsets are squeezed into what is
 * left before midnight, keeping their order (the feed's sky follows that order).
 */
const MAX_AHEAD = 7;
const laterToday = (hoursAhead: number): string => {
  const now = Date.now();
  const d = new Date(now + hoursAhead * 3600_000);
  d.setMinutes(0, 0, 0);
  const midnight = new Date(now);
  midnight.setHours(24, 0, 0, 0);
  if (d.getTime() > now && d.getTime() < midnight.getTime()) return d.toISOString();
  const left = midnight.getTime() - now;
  const step = 5 * 60_000;
  const t = now + Math.max(step, Math.floor(((left * 0.92 * hoursAhead) / MAX_AHEAD) / step) * step);
  return new Date(t).toISOString();
};

