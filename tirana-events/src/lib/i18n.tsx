/** Exported for the parity test; screens read copy through useI18n(). */
export const DICTS: Record<Lang, Dict> = { sq, en };
const dict = DICTS;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Dict;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('sq');
  // like the theme: hold the first paint until the saved language is known, so an
  // English user never sees the Albanian copy flash and then swap (a layout shift)
  const [ready, setReady] = useState(false);

  useEffect(() => {
    migrateStorage()
      .then(() => readString(KEYS.lang, LANGS))
      .then((v) => {
        if (v) setLangState(v);
      })
      .finally(() => setReady(true));
  }, []);

  const value = useMemo<I18nCtx>(
    () => ({
      lang,
      t: dict[lang],
      setLang: (l: Lang) => {
        setLangState(l);
        writeString(KEYS.lang, l);
      },
    }),
    [lang],
  );

  if (!ready) return null;
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n must be used inside <I18nProvider>');
  return v;
}
